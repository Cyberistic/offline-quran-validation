_cd = _ilu.module_from_spec(_spec)
_spec.loader.exec_module(_cd)

import torch
import torch.nn.functional as F

VOCAB_SIZE = 1025
BLANK_ID = VOCAB_SIZE - 1  # 1024

# Beam search params
BEAM_WIDTH = int(os.getenv("TRIE_BEAM_WIDTH", "100"))
PRUNE_THRESHOLD = float(os.getenv("TRIE_PRUNE_THRESHOLD", "-10.0"))
BLANK_PENALTY = float(os.getenv("TRIE_BLANK_PENALTY", "-3.0"))
N_CANDIDATES = int(os.getenv("TRIE_N_CANDIDATES", "50"))
MAX_VERSE_SPAN = int(os.getenv("TRIE_MAX_VERSE_SPAN", "6"))


_ort_session = None
_tokenizer = None
_trie = None
_verse_by_id = None


def _ensure_loaded():
    global _ort_session, _tokenizer, _trie, _verse_by_id
    if _ort_session is not None:
        return
    providers = ort.get_available_providers()
    if "CPUExecutionProvider" in providers:
        chosen = "CPUExecutionProvider"
    else:
        chosen = providers[0]
    onnx_path = ONNX_PATH if ONNX_PATH.exists() else FALLBACK_ONNX
    if not onnx_path.exists():
        raise FileNotFoundError(
            f"No ONNX at {ONNX_PATH} or {FALLBACK_ONNX}. Run scripts/export_fastconformer_onnx.py."
        )
    print(f"[c2c-direct-trie] loading {onnx_path.name} on {chosen}...")
    _ort_session = ort.InferenceSession(str(onnx_path), providers=[chosen])

    _cd._ensure_loaded()
    _tokenizer = _cd._model.tokenizer
    _trie, _verse_by_id = _build_trie(_cd._model)
    print(f"[c2c-direct-trie] built trie: {len(_trie['arcs_offset']) - 1} nodes, {len(_verse_by_id)} verses")


def _build_trie(model):
    """Build a flat trie from tokenized Quran verses (CSR arrays)."""
    from shared.normalizer import normalize_arabic
    import json

    quran_path = PROJECT_ROOT / "data" / "quran.json"
    with open(quran_path) as f:
        quran = json.load(f)

    trie_dict = {0: {}}
    terminals = {}
    verse_by_id = {}

    for verse in quran:
        text = normalize_arabic(verse["text_clean"])
        ids = model.tokenizer.text_to_ids(text)
        if not ids:
            continue
        verse_by_id[(verse["surah"], verse["ayah"])] = ids

        node = 0
        for tok in ids:
            nxt = trie_dict[node].get(tok)
            if nxt is None:
                nxt = len(trie_dict)
                trie_dict[node][tok] = nxt
                trie_dict[nxt] = {}
            node = nxt
        terminals.setdefault(node, []).append((verse["surah"], verse["ayah"]))

    arcs_token = []
    arcs_target = []
    arcs_offset = [0]
    for node in range(len(trie_dict)):
        for tok, nxt in sorted(trie_dict[node].items()):
            arcs_token.append(tok)
            arcs_target.append(nxt)
        arcs_offset.append(len(arcs_token))

    return {
        "arcs_token": np.array(arcs_token, dtype=np.int32),
        "arcs_target": np.array(arcs_target, dtype=np.int32),
        "arcs_offset": np.array(arcs_offset, dtype=np.int32),
        "terminals": terminals,
    }, verse_by_id


def _ctc_logprobs(audio_path: str) -> np.ndarray:
    _ensure_loaded()
    audio = _cd.load_audio(audio_path)
    arr = audio.reshape(1, -1).astype("float32")
    length = np.array([audio.shape[0]], dtype=np.int64)
    out = _ort_session.run(None, {"audio_signal": arr, "length": length})[0]
    return out[0]


def _beam_search_collect_verses(log_probs: np.ndarray) -> list[list[tuple[int, int]]]:
    """Hannun-style prefix beam search constrained to the verse trie.

    Returns a list of verse sequences (each a list of (surah, ayah)),
    sorted by length-normalized log-prob (best first). The trie ensures
    every returned sequence is a real Quran verse (or sequence of verses).
    """
    trie = _trie
    arcs_token = trie["arcs_token"]
    arcs_target = trie["arcs_target"]
    arcs_offset = trie["arcs_offset"]
    terminals = trie["terminals"]
    num_nodes = len(arcs_offset) - 1
    node_terminal_flag = np.zeros(num_nodes, dtype=bool)
    for n in terminals:
        node_terminal_flag[n] = True

    T, V = log_probs.shape
    lp = log_probs.copy()
    lp[:, BLANK_ID] += BLANK_PENALTY  # discourage staying at root
    NEG_INF = -1e10

    # State: (trie_node, last_token) -> (p_blank, p_nonblank, verses)
    state_pblank = {(0, BLANK_ID): 0.0}
    state_pnonblank = {(0, BLANK_ID): NEG_INF}
    state_verses = {(0, BLANK_ID): ()}

    for t in range(T):
        lp_t = lp[t]
        new_pblank = {}
        new_pnonblank = {}
        new_verses = {}

        for state_key, p_b in state_pblank.items():
            node, last = state_key
            p_nb = state_pnonblank[state_key]
            verses = state_verses[state_key]
            if p_nb == NEG_INF:
                p_total = p_b
            elif p_b == NEG_INF:
                p_total = p_nb
            else:
                p_total = max(p_b, p_nb) + math.log1p(math.exp(-abs(p_b - p_nb)))

            # Blank extension: stay at same node
            new_state = (node, BLANK_ID)
            cur_b = new_pblank.get(new_state, NEG_INF)
            blank_score = p_total + lp_t[BLANK_ID]
            if blank_score > cur_b:
                new_pblank[new_state] = blank_score
                if new_state not in new_verses:
                    new_verses[new_state] = verses

            # Non-blank extension: walk the trie
            children_start = arcs_offset[node]
            children_end = arcs_offset[node + 1]
            for i in range(children_start, children_end):
                tok = int(arcs_token[i])
                next_node = int(arcs_target[i])
                lp_tok = lp_t[tok]
                if lp_tok < -20:
                    continue
                if tok == last:
                    new_state = (node, last)
                    cur_nb = new_pnonblank.get(new_state, NEG_INF)
                    add = p_b + lp_tok
                    if add > cur_nb:
                        new_pnonblank[new_state] = add
                        if new_state not in new_verses:
                            new_verses[new_state] = verses
                else:
                    new_state = (next_node, tok)
                    cur_nb = new_pnonblank.get(new_state, NEG_INF)
                    add = p_total + lp_tok
                    if add > cur_nb:
                        new_pnonblank[new_state] = add
                        new_verses[new_state] = verses

            # Terminal restart: if at a terminal node, allow verse-end
            # transition to root (with cumulative verse in state_verses)
            if node_terminal_flag[node] and node != 0:
                for end_verse in terminals[node]:
                    new_verses_extended = verses + (end_verse,)
                    restart_state = (0, BLANK_ID)
                    cur_b = new_pblank.get(restart_state, NEG_INF)
                    restart_score = p_total + lp_t[BLANK_ID]
                    if restart_score > cur_b:
                        new_pblank[restart_state] = restart_score
                        new_verses[restart_state] = new_verses_extended

        # Prune
        all_states = set(new_pblank.keys()) | set(new_pnonblank.keys())
        scored = []
        for sk in all_states:
            pb = new_pblank.get(sk, NEG_INF)
            pnb = new_pnonblank.get(sk, NEG_INF)
            if pb == NEG_INF and pnb == NEG_INF:
                continue
            if pb == NEG_INF:
                s = pnb
            elif pnb == NEG_INF:
                s = pb
            else:
                s = max(pb, pnb) + math.log1p(math.exp(-abs(pb - pnb)))
            scored.append((s, sk))
        if not scored:
            break
        scored.sort(reverse=True, key=lambda x: x[0])
        best = scored[0][0]
        scored = [(s, sk) for s, sk in scored if s > best + PRUNE_THRESHOLD][:BEAM_WIDTH]
        state_pblank = {sk: new_pblank.get(sk, NEG_INF) for s, sk in scored}
        state_pnonblank = {sk: new_pnonblank.get(sk, NEG_INF) for s, sk in scored}
        state_verses = {sk: new_verses.get(sk, ()) for s, sk in scored}

    # Final: collect unique verse sequences
    final = {}
    for sk, pb in state_pblank.items():
        pnb = state_pnonblank[sk]
        if pb == NEG_INF and pnb == NEG_INF:
            continue
        if pb == NEG_INF:
            s = pnb
        elif pnb == NEG_INF:
            s = pb
        else:
            s = max(pb, pnb) + math.log1p(math.exp(-abs(pb - pnb)))
        verses = state_verses[sk]
        n_tok = max(1, sum(len(_verse_by_id[v]) for v in verses))
        norm_s = s / n_tok
        if verses:
            if verses not in final or norm_s > final[verses][0]:
                final[verses] = (norm_s, s)

    sorted_results = sorted(final.items(), key=lambda kv: kv[1][0], reverse=True)
    return [list(verses) for verses, _ in sorted_results[:N_CANDIDATES]]


def _ctc_rerank(log_probs_np: np.ndarray, candidates: list[list[tuple[int, int]]]) -> list[dict]:
    """Score each verse-sequence candidate via F.ctc_loss.

    Returns a list of dicts: {verses, surah, ayah, ayah_end, ctc_norm_loss, score}
    sorted by ctc_norm_loss (lowest = best).
    """
    t, _ = log_probs_np.shape
    log_probs = torch.from_numpy(log_probs_np).unsqueeze(1)  # [T, 1, V]

    # Build token sequences for each candidate (concatenated verses)
    encoded_seqs = []
    for verses in candidates:
        ids = []
        for v in verses:
            ids.extend(_verse_by_id.get(v, []))
        if not ids:
            encoded_seqs.append([])
        else:
            encoded_seqs.append(ids)

    # Filter to feasible (target_len * 2 + 1 <= T)
    feasible = [(i, seq) for i, seq in enumerate(encoded_seqs) if seq and len(seq) * 2 + 1 <= t]
    if not feasible:
        return []

    indices, seqs = zip(*feasible)
    n = len(seqs)
    targets = torch.tensor([tok for seq in seqs for tok in seq], dtype=torch.long)
    target_lengths = torch.tensor([len(seq) for seq in seqs], dtype=torch.long)
    input_lengths = torch.full((n,), t, dtype=torch.long)
    losses = F.ctc_loss(
        log_probs.expand(t, n, VOCAB_SIZE).contiguous(),
        targets,
        input_lengths,
        target_lengths,
        blank=BLANK_ID,
        reduction="none",
        zero_infinity=True,
    )
    norm_losses = losses / target_lengths.float()

    results = []
    for idx, raw_loss, norm_loss, length in zip(
        indices, losses.tolist(), norm_losses.tolist(), [len(s) for s in seqs]
    ):
        verses = candidates[idx]
        results.append({
            "verses": verses,
            "surah": verses[0][0],
            "ayah": verses[0][1],
            "ayah_end": verses[-1][1],
            "ctc_loss": float(raw_loss),
            "ctc_norm_loss": float(norm_loss),
            "ctc_len": int(length),
        })
    results.sort(key=lambda r: r["ctc_norm_loss"])
    return results


def _expand_to_spans(top_verses: list[list[tuple[int, int]]]) -> list[list[tuple[int, int]]]:
    """For each top single-verse candidate, generate multi-verse span candidates
    in the same surah (used by c2c-direct's _build_candidates).
    """
    out = list(top_verses)
    seen = {tuple(v) for v in top_verses}
    for single in top_verses[:20]:
        if not single:
            continue
        s, a = single[0]
        surah_verses = _cd._db.get_surah(s)
        max_ayah = surah_verses[-1]["ayah"] if surah_verses else a
        for end_a in range(a, min(max_ayah, a + MAX_VERSE_SPAN) + 1):
            span = [(s, x) for x in range(a, end_a + 1)]
            key = tuple(span)
            if key not in seen:
                seen.add(key)
                out.append(span)
    return out


def predict(audio_path: str) -> dict:
    _ensure_loaded()
    t0 = time.time()
    log_probs = _ctc_logprobs(audio_path)
    t_forward = time.time() - t0

    t0 = time.time()
    verse_candidates = _beam_search_collect_verses(log_probs)
    t_search = time.time() - t0

    # Expand single-verse hits to multi-verse spans in the same surah
    verse_candidates = _expand_to_spans(verse_candidates)

    t0 = time.time()
    ranked = _ctc_rerank(log_probs, verse_candidates)
    t_rerank = time.time() - t0

    if not ranked:
        return {
            "surah": 0,
            "ayah": 0,
            "ayah_end": None,
            "score": 0.0,
            "transcript": "",
            "source": "trie",
            "candidates": [],
        }

    best = ranked[0]
    score = math.exp(-best["ctc_norm_loss"]) if math.isfinite(best["ctc_norm_loss"]) else 0.0

    out_candidates = []
    for r in ranked[:5]:
        out_candidates.append({
            "surah": r["surah"],
            "ayah": r["ayah"],
            "ayah_end": r["ayah_end"],
            "score": round(-r["ctc_norm_loss"], 4),
            "verses": r["verses"],
        })

    return {
        "surah": best["surah"],
        "ayah": best["ayah"],
        "ayah_end": best["ayah_end"],
        "score": round(score, 4),
        "transcript": "",  # not meaningful with trie decoder
        "source": "trie",
        "candidates": out_candidates,
        "t_forward_s": round(t_forward, 3),
        "t_search_s": round(t_search, 3),
        "t_rerank_s": round(t_rerank, 3),
    }


def transcribe(audio_path: str) -> str:
    _ensure_loaded()
    return _cd._greedy_decode(_ctc_logprobs(audio_path))


def model_size() -> int:
    if ONNX_PATH.exists():
        return ONNX_PATH.stat().st_size
    if FALLBACK_ONNX.exists():
        return FALLBACK_ONNX.stat().st_size
    return 0
