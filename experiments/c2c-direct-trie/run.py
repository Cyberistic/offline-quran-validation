"""c2c-direct-trie — prefix-constrained CTC beam search candidate generation
+ CTC re-ranking (the same scoring as c2c-direct-mixed).

Improves over c2c-direct-mixed in one specific way: the candidate set is
generated by walking the verse trie via CTC beam search, so we get
**guaranteed in-vocabulary** verse sequences (no fuzzy-match garbage
when greedy decode picks an OOV path). The final pick is still the
candidate with the lowest CTC loss against the model's own log-probs,
which is what c2c-direct uses.

The deepsearch ranked this as the SOTA for closed-vocab ASR (WFST /
trie-based beam search with lexicon constraint). Our lexicon is the
6,236 verse texts; our beam search is Hannun-style prefix beam
search constrained to the verse trie.

Same FastConformer ONNX (data/onnx_export/fastconformer_full_mixed.onnx,
88 MB) and same BPE tokenizer as c2c-direct-mixed. The on-disk
budget is 88 MB.
"""

